export const totalProductCount = products.length;

export function findProductBySlug(slug: string): Product | undefined {
  return products.find((product) => product.slug === slug);
}

export function findProductById(id: string): Product | undefined {
  return products.find((product) => product.id === id);
}

export function featuredProducts(limit = 4): Product[] {
  return products.filter((product) => product.isFeatured).slice(0, limit);
}

/** Same department, excluding the product itself. */
export function relatedProducts(product: Product, limit = 4): Product[] {
  return products
    .filter((candidate) => candidate.category === product.category && candidate.id !== product.id)
    .slice(0, limit);
}

export function productCountByCategory(category: string): number {
  return products.filter((product) => product.category === category).length;
}

export function productCountByTier(tier: string): number {
  return products.filter((product) => product.tier === tier).length;
}
